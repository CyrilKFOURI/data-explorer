"""What happens to each column (rules R-SYN-01 to 08) and which method is recommended."""

from dataclasses import dataclass, field
from typing import Literal

from cyfouri_data_explorer.synthetic.encode import RARE
from cyfouri_data_explorer.synthetic.sequences import SequencePlan
from cyfouri_data_explorer.typing.types import AnalysisType

Treatment = Literal["model", "unique", "fake", "leave"]
Method = Literal["cart", "copula", "bayes", "independent", "ctgan", "tvae", "timegan"]

MAX_MODELLED = 100
MAX_TRAIN_ROWS = 50_000
MIN_ROWS = 50
MIN_GENERATED, MAX_GENERATED = 100, 1_000_000
MANY_LEVELS = 200  # R-SYN-08: above this, rare levels are grouped before learning
MOSTLY_EMPTY = 0.95
SMOOTH_REASON = (
    "On: continuous numbers stay off the real values, so far fewer rows copy a real one."
)

FAKE_ROLES = {"email", "phone", "url"}
TEXT_ROLES = FAKE_ROLES | {"free_text"}

METHODS: dict[Method, tuple[str, str]] = {
    "cart": ("Sequential CART", "Best fidelity on mixed columns: keeps non-linear links."),
    "copula": ("Gaussian copula", "Fast; keeps monotonic links between columns."),
    "bayes": ("Bayesian network", "Suited to mostly categorical data; shows its structure."),
    "independent": ("Independent columns", "Reference only: every link between columns is lost."),
    "ctgan": ("CTGAN", "Neural network (GAN): multimodal numbers and rare levels; needs training."),
    "tvae": (
        "TVAE",
        "Neural network (autoencoder): often the most faithful deep model; needs training.",
    ),
    "timegan": ("TimeGAN", "Neural network for sequences: keeps how each history moves over time."),
}
DEEP: set[Method] = {"ctgan", "tvae", "timegan"}
DEEP_MISSING = "Needs the deep extra (PyTorch): uv sync --extra deep."
LARGE_FOR_DEEP = 20_000  # training rows from which a ready GPU makes CTGAN worth suggesting


@dataclass
class PlanColumn:
    """A column of the source, as the plan needs it."""

    name: str
    type: AnalysisType
    role: str | None
    rows: int
    present: int  # non-empty values
    distinct: int
    excluded: bool = False


@dataclass
class ColumnPlan:
    name: str
    type: AnalysisType
    treatment: Treatment
    rule: str
    reason: str
    options: list[Treatment] = field(default_factory=list)  # what the user may pick instead
    grouped: bool = False  # R-SYN-08: rare levels grouped into "Other"


@dataclass
class MethodOption:
    key: Method
    label: str
    why: str
    available: bool = True
    unavailable: str | None = None  # why it cannot run here
    badge: str | None = None  # "Deep · GPU" or "Deep · CPU (slow)"
    epochs: int | None = None  # deep methods: automatic epochs (TimeGAN: steps per phase)


@dataclass
class Plan:
    columns: list[ColumnPlan]
    method: Method
    method_reason: str
    methods: list[MethodOption]
    rows: int  # rows in the source
    default_rows: int  # rows generated by default
    train_rows: int  # rows the generator learns from
    modelled: int
    error: str | None = None  # why nothing can be generated
    smooth: bool = True  # CART: noise on numbers by default
    smooth_reason: str = SMOOTH_REASON
    gpu: str | None = None  # the card the deep methods would train on (None: the CPU)
    sequence: SequencePlan | None = None  # TimeGAN: time, entity, length (023c)


def _treat(column: PlanColumn) -> ColumnPlan:
    kind, role = column.type, column.role
    missing = 1 - column.present / column.rows if column.rows else 1.0

    def plan(treatment: Treatment, rule: str, reason: str, options: list[Treatment]) -> ColumnPlan:
        return ColumnPlan(column.name, kind, treatment, rule, reason, options)

    if column.excluded or kind == "ignored":
        return plan("leave", "R-SYN-07", "Excluded in Columns.", [])
    if missing > MOSTLY_EMPTY:
        return plan("leave", "R-SYN-07", f"{missing:.0%} of the values are empty.", ["model"])
    if kind == "text" or role in TEXT_ROLES:
        if role in FAKE_ROLES:
            options: list[Treatment] = ["leave", "fake"]
            if kind == "identifier":
                options.append("unique")
            return plan(
                "leave",
                "R-SYN-06",
                f"Left out: a real {role} could leak. Fake values in the same format are possible.",
                options,
            )
        return plan("leave", "R-SYN-06", "Free text could leak real content.", ["leave"])
    if kind == "identifier" or role == "identifier":
        return plan(
            "unique",
            "R-SYN-05",
            "New identifiers in the same format; never a real value.",
            ["unique", "leave"],
        )
    if kind == "numeric_continuous":
        reason = "Modelled; real bounds and decimals kept."
        return plan("model", "R-SYN-01", reason, ["model", "leave"])
    if kind == "numeric_discrete":
        return plan("model", "R-SYN-02", "Modelled; rounded to whole numbers.", ["model", "leave"])
    if kind == "datetime":
        reason = "Modelled as a number of seconds, converted back to dates."
        return plan("model", "R-SYN-04", reason, ["model", "leave"])
    if column.distinct > MANY_LEVELS:
        result = plan(
            "model",
            "R-SYN-08",
            f'{column.distinct} levels: those seen fewer than {RARE} times become "Other".',
            ["model", "unique", "leave"],
        )
        result.grouped = True
        return result
    return plan(
        "model", "R-SYN-03", "Modelled; only existing levels are produced.", ["model", "leave"]
    )


def method_options(
    train_rows: int, deep_installed: bool, gpu: str | None, sequence_error: str | None = None
) -> list[MethodOption]:
    from cyfouri_data_explorer.synthetic.deep import (
        TIMEGAN_CPU_STEPS,
        TIMEGAN_GPU_STEPS,
        auto_epochs,
    )

    options = []
    for key, (label, why) in METHODS.items():
        option = MethodOption(key, label, why)
        if key in DEEP:
            option.available, option.unavailable = (
                deep_installed,
                None if deep_installed else DEEP_MISSING,
            )
            option.badge = "Deep · GPU" if gpu else "Deep · CPU (slow)"
            option.epochs = (
                auto_epochs(train_rows, gpu is not None)
                if key != "timegan"
                else (TIMEGAN_GPU_STEPS if gpu else TIMEGAN_CPU_STEPS)  # steps per phase
            )
            if key == "timegan" and deep_installed and sequence_error:
                option.available, option.unavailable = False, sequence_error
            if key == "ctgan" and gpu and train_rows >= LARGE_FOR_DEEP:
                option.why += " Worth trying here: many rows and a ready GPU."
        options.append(option)
    return options


def make_plan(
    columns: list[PlanColumn],
    rows: int,
    deep_installed: bool = False,
    gpu: str | None = None,
    sequence: SequencePlan | None = None,
) -> Plan:
    """`gpu`: the ready card the deep methods may use (None: they train on the CPU)."""
    planned = [_treat(c) for c in columns]
    modelled = [p for p in planned if p.treatment == "model"]
    for extra in modelled[MAX_MODELLED:]:
        extra.treatment, extra.rule = "leave", "R-SYN-07"
        extra.reason = f"Over the {MAX_MODELLED}-column limit."
    count = min(len(modelled), MAX_MODELLED)
    error = None
    if rows < MIN_ROWS:
        error = f"Needs at least {MIN_ROWS} rows (this data has {rows})."
    elif count == 0:
        error = "No column can be modelled: include numbers, categories or dates in Columns."
    label, why = METHODS["cart"]
    train_rows = min(int(rows * 0.8), MAX_TRAIN_ROWS)
    return Plan(
        planned,
        "cart",
        f"{label}: {why[0].lower()}{why[1:]}",
        method_options(
            train_rows,
            deep_installed,
            gpu,
            sequence.error if sequence else "Needs a date column.",
        ),
        rows,
        min(max(rows, MIN_GENERATED), MAX_GENERATED),
        train_rows,
        count,
        error,
        gpu=gpu if deep_installed else None,
        sequence=sequence,
    )
