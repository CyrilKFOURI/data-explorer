"""What the synthetic-data module lets the AI agent do (spec 026b): read the automatic plan,
generate a synthetic copy with its fidelity and privacy report, and save it as a dataset."""

from typing import Any, ClassVar, Literal

from fastapi import FastAPI
from pydantic import BaseModel, Field

from app.core.errors import AppError
from app.core.tools import AppLink, Tool, ToolContext, ToolError, ToolOutput, compact, wait_for
from app.modules.synthetic.service import RunRequest, SyntheticService

GENERATE_TIMEOUT = 900.0


def _link(run_id: str | None = None) -> AppLink:
    return AppLink("synthetic", {"run": run_id} if run_id else {}, "Open in Synthetic data")


class NoInput(BaseModel):
    pass


class PlanSynthetic(Tool[NoInput]):
    name: ClassVar[str] = "plan_synthetic"
    description: ClassVar[str] = (
        "The automatic plan for a synthetic copy of the dataset: how each column is treated "
        "(modelled, regenerated identifiers, left out free text…), the recommended method and "
        "why, the methods available, rows generated by default."
    )
    Input: ClassVar[type[BaseModel]] = NoInput

    def __init__(self, service: SyntheticService) -> None:
        self.service = service

    def label(self, args: NoInput) -> str:
        return "Planning a synthetic copy"

    def run(self, ctx: ToolContext, args: NoInput) -> ToolOutput:
        plan = self.service.plan(ctx.dataset_id)
        content = compact(plan, max_items=40)
        return ToolOutput(f"Recommended method: {plan.method}", content, _link())


class GenerateInput(BaseModel):
    method: Literal["cart", "copula", "bayes", "independent", "ctgan", "tvae"] = Field(
        "cart",
        description="Generator; the plan's recommendation is usually best (deep ones are slow).",
    )
    rows: int | None = Field(
        None, ge=100, le=1_000_000, description="Rows to generate; empty: as many as the source."
    )


class GenerateSynthetic(Tool[GenerateInput]):
    name: ClassVar[str] = "generate_synthetic"
    kind = "compute"
    description: ClassVar[str] = (
        "Generate a synthetic copy and evaluate it: overall fidelity and privacy scores with "
        "verdicts, how well columns and links between them are kept, whether a classifier can "
        "tell real from synthetic, and privacy checks (copies of real rows, distance to the "
        "closest real row). Saved as a run. Can take minutes."
    )
    Input: ClassVar[type[BaseModel]] = GenerateInput

    def __init__(self, service: SyntheticService) -> None:
        self.service = service

    def label(self, args: GenerateInput) -> str:
        return f"Generating synthetic data ({args.method})"

    def run(self, ctx: ToolContext, args: GenerateInput) -> ToolOutput:
        try:
            job = self.service.start(ctx.dataset_id, RunRequest(method=args.method, rows=args.rows))
        except AppError as error:
            raise ToolError(error.message) from error
        job = wait_for(
            lambda: self.service.job(job.id),
            lambda j: j.status != "running",
            ctx,
            describe=lambda j: (j.message or f"Stage: {j.stage}", j.progress),
            cancel=lambda: self.service.cancel(job.id),
            timeout=GENERATE_TIMEOUT,
        )
        if job.status != "done" or not job.run_id:
            raise ToolError(f"Generation {job.status}: {job.error or 'no detail'}")
        run = self.service.run(ctx.dataset_id, job.run_id)
        report = run.report
        content = {
            "run_id": run.id,
            "method": run.method_label,
            "rows": run.rows,
            "seconds": round(run.seconds, 1),
            "scores": compact(report.scores),
            "verdicts": compact(report.verdicts),
            "columns": compact(report.columns, max_items=15),
            "detection": compact(report.detection, max_items=8),
            "privacy": compact(report.privacy, max_items=8),
        }
        return ToolOutput(
            f"{run.method_label}: {run.rows:,} rows generated", content, _link(run.id)
        )


class SaveInput(BaseModel):
    run_id: str = Field(description="The run of generate_synthetic to save.")


class SaveSyntheticDataset(Tool[SaveInput]):
    name: ClassVar[str] = "save_synthetic_dataset"
    kind = "write"
    description: ClassVar[str] = (
        "Import a synthetic run's rows as a new dataset (with the source's column types), so it "
        "can be explored or shared. The user confirms first."
    )
    Input: ClassVar[type[BaseModel]] = SaveInput

    def __init__(self, service: SyntheticService) -> None:
        self.service = service

    def label(self, args: SaveInput) -> str:
        return "Saving the synthetic data as a dataset"

    def confirmation(self, args: SaveInput) -> str:
        return "Create a new dataset from this synthetic run (the source stays as it is)."

    def run(self, ctx: ToolContext, args: SaveInput) -> ToolOutput:
        try:
            created = self.service.create_dataset(ctx.dataset_id, args.run_id)
        except AppError as error:
            raise ToolError(error.message) from error
        return ToolOutput(
            "New dataset created",
            {"dataset_id": created},
            AppLink("dataset", {"dataset": created}, "Open the new dataset"),
        )


def agent_tools(app: FastAPI) -> list[Tool[Any]]:
    service: SyntheticService = app.state.synthetic
    return [PlanSynthetic(service), GenerateSynthetic(service), SaveSyntheticDataset(service)]
